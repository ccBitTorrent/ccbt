"""Generate dev/tui-inventory.txt: bindings x actions x screens x executor commands."""
from __future__ import annotations
import pathlib, re, sys
ROOT = pathlib.Path(__file__).resolve().parents[2]
iface = ROOT / "ccbt" / "interface"
dash = (iface / "terminal_dashboard.py").read_text(encoding="utf-8", errors="ignore")
actions = sorted(set(a.removeprefix("action_") for a in re.findall(r"async def (action_\w+)", dash)))
# Also actions defined in new domain screens count as reachable surfaces
all_iface = "\n".join(p.read_text(encoding="utf-8", errors="ignore") for p in iface.rglob("*.py"))
try:
    sys.path.insert(0, str(ROOT))
    from ccbt.interface.bindings import BINDING_SPECS
    bound = sorted({s.action for s in BINDING_SPECS})
    keys = sorted({f"{s.key}->{s.action}" for s in BINDING_SPECS})
except Exception:
    bound, keys = [], []
exec_cmds = set()
for p in (ROOT / "ccbt" / "executor").rglob("*.py"):
    exec_cmds.update(re.findall(r'["\']([a-z]+\.[a-z_0-9]+)["\']', p.read_text(encoding="utf-8", errors="ignore")))
used = set(re.findall(r'["\']([a-z]+\.[a-z_0-9]+)["\']', all_iface))
screens = sorted(set(re.findall(r"class (\w+(?:Screen|TabContent|Widget|Panel))\b", all_iface)))
lines = ["# TUI inventory (generated by dev/scripts/generate_tui_inventory.py)", "",
    f"actions={len(actions)} bound_actions={len(bound)} screens_widgets={len(screens)} executor_cmds={len(exec_cmds)} used_cmds={len(exec_cmds & used)}", "",
    "## Binding keys", *keys, "", "## Actions without binding (exempt: quit/back/yes/no system)", *[a for a in actions if a not in bound],
    "", "## Bindings without action", *[a for a in bound if a not in actions],
    "", "## Executor commands not referenced in interface (exempt if listed in docs)", *[c for c in sorted(exec_cmds - used)],
    "", "## Screens/widgets", *screens]
out = ROOT / "dev" / "tui-inventory.txt"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out}: actions={len(actions)} bound={len(bound)} unreachable_exec={len(exec_cmds-used)}")
